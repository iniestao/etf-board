def wrap(node) -> str:
    """需要优先级的子表达式套一层括号。

    运算符优先级一丢，`(close-low)-(high-close)` 就写成 `close-low-high-close`，
    `a / ((l-h)*c**5)` 就写成 `a / (l-h) * c**5`——公式从「能对着算」变成「看着像另一回事」。
    宁可多几个括号。
    """
    s = emit(node)
    # Compare / BoolOp 自己就带括号，再套一层会变成 (((a > 0))) 这种噪音
    if isinstance(node, ast.BinOp):
        return '(' + s + ')'
    return s


def emit(node) -> str:
    """把 AST 写成可读公式。

    不是简单套源码：`_w(cond, a, b)` 要展开成三元式，`self.c` 要换成 close，
    而 `ts_stddev(x, 20)` 里的逗号不能被当成 `_w` 的参数分隔符——
    早期版本用正则做这件事，a001 就被切成了 `ts_stddev(returns : 20)`。
    走 AST 之后，嵌套多深都不会错。
    """
    if isinstance(node, ast.Constant):
        v = node.value
        return ('True' if v is True else 'False' if v is False
                else repr(v) if isinstance(v, str) else str(v))
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        # `(c - o).abs()` 必须先给括号：直接拼字符串会变成 `c - o.abs()`，
        # 意思从「收盘减开盘的绝对值」变成「收盘减去开盘的绝对值」，完全另一回事。
        if node.attr == 'abs':
            return 'abs(' + emit(node.value) + ')'
        if isinstance(node.value, ast.BinOp):
            return '(' + emit(node.value) + ').' + node.attr
        if isinstance(node.value, ast.Name) and node.value.id == 'self':
            if node.attr == 'groups':
                return 'asset_class'
            return FIELD.get('self.' + node.attr, (node.attr, ''))[0]
        return f'{emit(node.value)}.{node.attr}'
    if isinstance(node, ast.BinOp):
        return f'{wrap(node.left)} {BINOP.get(type(node.op), "?")} {wrap(node.right)}'
    if isinstance(node, ast.UnaryOp):
        if isinstance(node.op, ast.USub):
            return '−' + emit(node.operand)
        if isinstance(node.op, ast.Not):
            return 'not ' + emit(node.operand)
        return emit(node.operand)
    if isinstance(node, ast.BoolOp):
        op = ' and ' if isinstance(node.op, ast.And) else ' or '
        return '(' + op.join(emit(v) for v in node.values) + ')'
    if isinstance(node, ast.Compare):
        parts = [wrap(node.left)]
        for op, right in zip(node.ops, node.comparators):
            parts.append(CMPOP.get(type(op), '?'))
            parts.append(wrap(right))
        return '(' + ' '.join(parts) + ')'
    if isinstance(node, ast.Call):
        # `x.abs()` 走的是 Call(Attribute)，不在这里拦就会被拼成 `abs(x)()`
        if isinstance(node.func, ast.Attribute) and node.func.attr == 'abs':
            return 'abs(' + emit(node.func.value) + ')'
        fn = emit(node.func)
        args = [wrap(a) for a in node.args]
        if fn == '_w' and len(args) == 3:
            return f'({args[0]} ? {args[1]} : {args[2]})'
        if fn == 'safe_div' and len(args) == 2:
            return f'{args[0]} ÷ {args[1]}'
        return f'{fn}(' + ', '.join(args) + ')'
    if isinstance(node, ast.Subscript):
        return f'{emit(node.value)}[{emit(node.slice)}]'
    if isinstance(node, ast.Tuple):
        return '(' + ', '.join(emit(e) for e in node.elts) + ')'
    seg = ast.get_source_segment(SRC.read_text(encoding='utf-8'), node) or ''
    return re.sub(r'\s+', ' ', seg).strip()


def seg(text: str, node) -> str:
    s = ast.get_source_segment(text, node) or ''
    return re.sub(r'\s+', ' ', s).strip()


def main() -> None:
    text = SRC.read_text(encoding='utf-8')
    tree = ast.parse(text)
    cls = next(n for n in tree.body
               if isinstance(n, ast.ClassDef) and n.name == 'Alpha101')
    fns = {n.name: n for n in cls.body
           if isinstance(n, ast.FunctionDef) and re.fullmatch(r'a\d{3}', n.name)}

    meta = {}
    for name in sorted(fns):
        fn = fns[name]
        steps, ret = [], None
        for st in fn.body:
            if isinstance(st, ast.Assign) and len(st.targets) == 1 and isinstance(st.targets[0], ast.Name):
                steps.append((st.targets[0].id, st.value))
            elif isinstance(st, ast.Return):
                ret = st.value
        if not ret:
            continue

        lines = [f'{k} = {emit(v)}' for k, v in steps if k != 'None']
        lines.append('→ ' + emit(ret))
        formula = '\n'.join(lines)

        nm, ds = ZH.get(name, (name.upper(), ''))
        meta[name] = {'nm': nm, 'ds': ds, 'f': formula}

    missing = [k for k in fns if k not in ZH]
    if missing:
        print('缺中文解读：', missing)

    body = json.dumps(meta, ensure_ascii=False, separators=(',', ':'))
    OUT.write_text(
        '// 由 tools/gen_alpha_meta.py 生成，勿手改\n'
        '// 公式来自 alpha/alpha101.py 的 AST，和实际在算的代码永远一致\n'
        f'export const ALPHA_META = {body};\n',
        encoding='utf-8',
    )
    print(f'已生成 {OUT.relative_to(ROOT)}  {len(meta)} 个因子  {len(body) / 1024:.1f} KB')


if __name__ == '__main__':
    main()
